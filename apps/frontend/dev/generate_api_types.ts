/**
 * Regenerates src/lib/api/schema.d.ts from the Go backend's OpenAPI spec.
 * The backend must be running (`make dev` in backend/); pass another spec
 * URL or file as the first argument if it isn't at the default address.
 *
 *   pnpm generate:api [url-or-path]
 *
 * File fields (`format: binary`) become `Blob`s instead of strings, so
 * uploads can be typed - see `multipart` in src/lib/api/client.ts.
 */
import fs from "node:fs";
import openapiTS, { astToString } from "openapi-typescript";
import ts from "typescript";
import * as prettier from "prettier";

const source = process.argv[2] ?? "http://localhost:8090/openapi.json";
const output = "src/lib/api/schema.d.ts";

const BLOB = ts.factory.createTypeReferenceNode(
  ts.factory.createIdentifier("Blob"),
);

const ast = await openapiTS(
  source.startsWith("http") ? new URL(source) : fs.readFileSync(source, "utf8"),
  {
    transform(schemaObject) {
      if (schemaObject.format === "binary") return BLOB;
    },
  },
);

const header =
  "/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n";
const code = header + astToString(ast);
const config = await prettier.resolveConfig(output);
fs.writeFileSync(
  output,
  await prettier.format(code, { ...config, filepath: output }),
);
console.log(`Wrote ${output}`);
