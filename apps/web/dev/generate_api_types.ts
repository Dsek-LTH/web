/**
 * Regenerates src/lib/api/schema.d.ts from the Go backend's OpenAPI spec,
 * which `go run ./cmd/openapi` prints without a running server or database.
 * Pass a spec URL or file as the first argument to use that instead.
 *
 *   pnpm generate:api [url-or-path]
 *
 * CI fails when the committed file differs from what this generates.
 *
 * File fields (`format: binary`) become `Blob`s instead of strings, so
 * uploads can be typed - see `multipart` in src/lib/api/client.ts.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import openapiTS, { astToString } from "openapi-typescript";
import ts from "typescript";
import * as prettier from "prettier";

const source = process.argv[2];
const output = "src/lib/api/schema.d.ts";

const BLOB = ts.factory.createTypeReferenceNode(
  ts.factory.createIdentifier("Blob"),
);

const spec =
  source === undefined
    ? execFileSync("go", ["run", "./cmd/openapi"], {
        cwd: "../api",
        encoding: "utf8",
        maxBuffer: 64 * 1024 * 1024,
      })
    : source.startsWith("http")
      ? new URL(source)
      : fs.readFileSync(source, "utf8");

const ast = await openapiTS(spec, {
  transform(schemaObject) {
    if (schemaObject.format === "binary") return BLOB;
  },
});

const header =
  "/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n";
const code = header + astToString(ast);
const config = await prettier.resolveConfig(output);
fs.writeFileSync(
  output,
  await prettier.format(code, { ...config, filepath: output }),
);
console.log(`Wrote ${output}`);
