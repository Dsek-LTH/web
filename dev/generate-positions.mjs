// Generates src/lib/actic/positions.ts from the @preview/dsek package's
// strings module, so the position dropdown stays in sync with the package.
//
// Run with: node dev/generate-positions.mjs
// Bump DSEK_PACKAGE_VERSION in src/lib/actic/dsek.ts and re-run when the
// package version changes. Requires network access.
import { writeFileSync } from "node:fs";

const REF = process.env.DSEK_REF ?? "main";
const URL = `https://raw.githubusercontent.com/Dsek-LTH/dsek-typst/${REF}/src/lib/assets/strings.typ`;

const src = await fetch(URL).then((r) => r.text());

// `guild` is a list of names, `lth-symbols` are glyphs, not positions.
const SKIP = new Set(["guild", "lth-symbols"]);
const ORDER = [
  "styr",
  "aktu",
  "infu",
  "cafe",
  "skattm",
  "fram",
  "km",
  "nollu",
  "naru",
  "sexm",
  "srd",
  "cpu",
  "medalj",
  "valb",
  "tackm",
  "triv",
  "otherpos",
];

const clean = (s) => s.replace(/-\?/g, "").replace(/\s+/g, " ").trim();

// Groups without a `name` entry in strings.typ need a display label.
const GROUP_LABELS = {
  otherpos: { sv: "Övriga", en: "Other" },
};

const groups = {};
const groupRe = /#let ([\w-]+) = \(\n([\s\S]*?)\n\)/g;
let m;
while ((m = groupRe.exec(src))) {
  const [, gname, body] = m;
  if (SKIP.has(gname)) continue;
  const entryRe =
    /"([\w-]+)":\s*translate\(\s*\[([\s\S]*?)\]\s*,\s*\[([\s\S]*?)\]\s*\)/g;
  const entries = [];
  let e;
  while ((e = entryRe.exec(body))) {
    entries.push({ key: e[1], sv: clean(e[2]), en: clean(e[3]) });
  }
  if (entries.length) groups[gname] = entries;
}

const lines = [
  "// AUTO-GENERATED by dev/generate-positions.mjs from @preview/dsek's",
  "// src/lib/assets/strings.typ. Regenerate when the pinned package version",
  "// changes (see DSEK_PACKAGE_VERSION in dsek.ts).",
  "// Source: https://github.com/Dsek-LTH/dsek-typst",
  "",
  "export type Position = { key: string; label: string; labelEn: string };",
  "export type PositionGroup = {",
  "  key: string;",
  "  label: string;",
  "  labelEn: string;",
  "  positions: Position[];",
  "};",
  "",
  "export const POSITION_GROUPS: PositionGroup[] = [",
];
for (const gname of ORDER) {
  const entries = groups[gname];
  if (!entries) continue;
  const name = entries.find((x) => x.key === "name");
  const positions = entries.filter((x) => x.key !== "name");
  const fallback = GROUP_LABELS[gname];
  lines.push("  {");
  lines.push(`    key: ${JSON.stringify(gname)},`);
  lines.push(
    `    label: ${JSON.stringify(name?.sv ?? fallback?.sv ?? gname)},`,
  );
  lines.push(
    `    labelEn: ${JSON.stringify(name?.en ?? fallback?.en ?? gname)},`,
  );
  lines.push("    positions: [");
  for (const p of positions) {
    lines.push(
      `      { key: ${JSON.stringify(p.key)}, label: ${JSON.stringify(p.sv)}, labelEn: ${JSON.stringify(p.en)} },`,
    );
  }
  lines.push("    ],");
  lines.push("  },");
}
lines.push("];", "");
lines.push(
  "/** Flat list of every position, with its Typst key path (`group.key`). */",
);
lines.push("export const ALL_POSITIONS: Array<{");
lines.push("  path: string;");
lines.push("  label: string;");
lines.push("  labelEn: string;");
lines.push("  group: string;");
lines.push("  groupEn: string;");
lines.push("}> = POSITION_GROUPS.flatMap((g) =>");
lines.push("  g.positions.map((p) => ({");
lines.push("    path: `${g.key}.${p.key}`,");
lines.push("    label: p.label,");
lines.push("    labelEn: p.labelEn,");
lines.push("    group: g.label,");
lines.push("    groupEn: g.labelEn,");
lines.push("  })),");
lines.push(");");
lines.push("");

const out = new URL("../src/lib/actic/positions.ts", import.meta.url);
writeFileSync(out, lines.join("\n"));
const total = Object.values(groups).reduce((a, b) => a + b.length, 0);
console.log(
  `Wrote ${out.pathname} — ${Object.keys(groups).length} groups, ${total} entries`,
);
